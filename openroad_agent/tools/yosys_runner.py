"""Tool: run Yosys synthesis and capture output/metrics.

Supports two execution modes (matching openroad_runner):
  - "local":  subprocess on this machine
  - "ray":    submit to a remote Ray-on-K8s cluster

The mode is controlled by ``OPENROAD_EXEC_MODE`` env var.
"""

