# ── lazy config ────────────────────────────────────────────────────────
_cfg_instance: OpenROADConfig | None = None


def _get_cfg() -> OpenROADConfig:
    global _cfg_instance
    if _cfg_instance is None:
        _cfg_instance = OpenROADConfig()
    return _cfg_instance


# ── Default Yosys synthesis script template ────────────────────────────
# This is a self-contained Yosys TCL script that performs a complete
# RTL → gate-level netlist synthesis targeting a Liberty cell library.
# It mirrors the key steps from OpenROAD-flow-scripts/flow/scripts/synth*.tcl
# but is self-contained (no external env vars required beyond what we set).

YOSYS_SYNTH_TEMPLATE = r"""# ================================================================
# Yosys Synthesis Script  (auto-generated by openroad_agent)
# Design : {design_name}
# Top    : {top_module}
# Platform: {platform}
# ================================================================
yosys -import

# ── Read Liberty for cell mapping ──────────────────────────
{read_liberty_cmds}

# ── Read Verilog source(s) ─────────────────────────────────
{read_verilog_cmds}

# ── Synthesis ──────────────────────────────────────────────
hierarchy -check -top {top_module}
{synth_args_line}

# ── Technology mapping ─────────────────────────────────────
# Flip-flop mapping
dfflibmap -liberty {liberty_for_abc}

# Combinational mapping via ABC
{abc_line}

# ── Cleanup ────────────────────────────────────────────────
opt -purge
setundef -zero
splitnets
opt_clean -purge

{tiehi_tielo_cmds}
{insbuf_cmd}

# ── Reports ────────────────────────────────────────────────
tee -o {reports_dir}/synth_check.txt check
tee -o {reports_dir}/synth_stat.txt stat {stat_liberty_args}

# ── Write output ───────────────────────────────────────────
write_verilog -noattr -noexpr -nohex -nodec {output_verilog}
"""

