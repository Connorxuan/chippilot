@tool
def run_yosys_synthesis(
    synth_script: str,
    run_label: str = "synth",
    timeout_seconds: int = 1800,
) -> str:
    """Execute a Yosys synthesis TCL/command script and return results.

    Execution happens locally or on the remote Ray cluster depending on
    the ``OPENROAD_EXEC_MODE`` setting ("local" or "ray").

    Args:
        synth_script: Complete Yosys TCL/command script content.
        run_label: Short label for file naming.
        timeout_seconds: Max wall-clock seconds.

    Returns:
        JSON with keys: success, stdout, stderr, metrics, elapsed_s,
        result_files, run_dir, remote, tool ("yosys").
    """
    cfg = _get_cfg()

    # Fix literal escape sequences from LLM
    if '\\n' in synth_script:
        synth_script = synth_script.replace('\\n', '\n')
    if '\\t' in synth_script:
        synth_script = synth_script.replace('\\t', '\t')

    # Ensure any write_verilog with a bare filename goes into __RESULTS_DIR__
    # so the output lands in the run directory (not in the CWD).
    synth_script = _fix_write_verilog_paths(synth_script)

    if cfg.execution_mode == "ray":
        return _run_yosys_via_ray(cfg, synth_script, run_label, timeout_seconds)
    return _run_yosys_locally(cfg, synth_script, run_label, timeout_seconds)


@tool
def generate_yosys_synth_script(
    design_name: str,
    top_module: str,
    platform: str,
    verilog_files: list[str],
    output_verilog: str = "",
    clock_period_ps: float = 0,
    flatten: bool = True,
    abc_area: bool = False,
) -> str:
    """Generate a Yosys synthesis script for the given design and platform.

    This builds a ready-to-run Yosys TCL script that reads the RTL Verilog,
    synthesises it with ABC, maps to the target cell library, and writes
    a gate-level netlist.

    Args:
        design_name: Design name (e.g. "gcd").
        top_module: Top-level module name.
        platform: Target PDK ("nangate45", "sky130hd", "sky130hs", "asap7").
        verilog_files: List of Verilog source file paths (relative to test dir).
        output_verilog: Output netlist path (default: results/<design>_synth.v).
        clock_period_ps: Clock period in ps for timing-driven ABC (0 = disable).
        flatten: Flatten hierarchy during synthesis.
        abc_area: Use area-optimised ABC script.

    Returns:
        The generated Yosys synthesis script as a string.
    """
    cfg = _get_cfg()

    # Use placeholders — the runner will substitute the actual paths
    reports_dir = "__REPORTS_DIR__"
    results_dir = "__RESULTS_DIR__"

    if not output_verilog:
        output_verilog = f"{results_dir}/{design_name}_synth.v"
    elif "__RESULTS_DIR__" not in output_verilog and not os.path.isabs(output_verilog):
        # Bare filename like "riscv32i_synth.v" — must go into results dir
        # so that the remote runner can find it and sync it back.
        output_verilog = f"{results_dir}/{output_verilog}"

    script = build_yosys_synth_script(
        design_name=design_name,
        top_module=top_module,
        platform=platform,
        verilog_files=verilog_files,
        output_verilog=output_verilog,
        reports_dir=reports_dir,
        clock_period_ps=clock_period_ps if clock_period_ps > 0 else None,
        flatten=flatten,
        abc_area=abc_area,
        base_dir=cfg.test_dir,
    )
    return script


@tool
def list_synth_platforms() -> str:
    """List platforms supported for Yosys synthesis with their key params.

    Returns:
        JSON with platform names and synthesis parameters.
    """
    info = {}
    for plat, params in _PLATFORM_SYNTH_PARAMS.items():
        info[plat] = {
            "liberty_files": params["liberty_files"],
            "dont_use_cells": params["dont_use_cells"][:3],
            "tie_cells": f"{params['tiehi_cell_and_port']} / {params['tielo_cell_and_port']}",
        }
    return json.dumps(info, indent=2)
